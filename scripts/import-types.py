#!/usr/bin/env python3
"""Re-declares the record/enum types of the sibling app's UniFFI bindings as
plain Swift types with Codable conformances.

The SwiftUI front end was written against UniFFI-generated types. qBittorrent
Neo exchanges data with the C++ core as JSON, so this script copies the type
declarations (fields, initializers, doc comments) from a generated
`qbt_core.swift`, drops all FFI glue and adds:

* records: `Codable` with a lenient decoder (missing keys fall back to
  zero/empty/nil/defaults), field names unchanged (camelCase JSON keys);
* simple enums: `Codable` as a plain JSON string with the case name;
* enums with associated values: synthesized `Codable`
  (`{"caseName": {"label": value}}`);
* `Sendable` for everything.

Usage: import-types.py <qbt_core.swift> <output.swift>
"""
import re
import sys

SIMPLE_DEFAULTS = {
    "String": '""', "Bool": "false", "Data": "Data()", "Double": "0", "Float": "0",
    "Int8": "0", "Int16": "0", "Int32": "0", "Int64": "0",
    "UInt8": "0", "UInt16": "0", "UInt32": "0", "UInt64": "0",
}


KEYWORDS = {"private", "public", "internal", "default", "protocol", "class", "struct", "enum", "func",
            "var", "let", "in", "for", "if", "else", "return", "switch", "case", "where", "is", "as", "self"}


def esc(name):
    return f"`{name}`" if name in KEYWORDS else name


def block_end(lines, start):
    depth = 0
    for i in range(start, len(lines)):
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0 and "{" in "".join(lines[start:i + 1]):
            return i
    raise ValueError(f"unbalanced block at {start}")


def doc_start(lines, start):
    i = start
    if i > 0 and lines[i - 1].strip() == "*/":
        while not lines[i - 1].strip().startswith("/**"):
            i -= 1
        i -= 1
    return i


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = open(src, encoding="utf-8").read().split("\n")
    records, enums = [], []
    chunks = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^public (struct|enum) (\w+): Equatable, Hashable \{", line)
        err = line.strip() == "public" and i + 1 < len(lines) and lines[i + 1].startswith("enum QbtError")
        proto = line.startswith("public protocol EventListener:")
        if m or err or proto:
            end = block_end(lines, i)
            start = doc_start(lines, i)
            body = lines[start:end + 1]
            text = "\n".join(l.rstrip() for l in body)
            text = re.sub(r"\(\s*([^()]*?)\s*\n\s*\)", r"(\1)", text)  # join wrapped case params
            text = re.sub(r"\n{3,}", "\n\n", text)
            text = text.replace("public \nenum QbtError", "public enum QbtError")
            chunks.append(text)
            if m and m.group(1) == "struct":
                fields = [(n.strip("`"), t) for n, t in re.findall(r"^    public var (`?\w+`?): (.+)$", "\n".join(body), re.M)]
                records.append((m.group(2), fields))
            elif m:
                cases = re.findall(r"^    case (`?\w+`?)(\(.*\))?$", text, re.M)
                enums.append((m.group(2), cases))
            i = end + 1
            continue
        i += 1

    record_names = {r[0] for r in records}
    enum_info = {e[0]: e[1] for e in enums}

    def default_for(t):
        t = t.strip()
        if t.endswith("?"):
            return None
        if t in SIMPLE_DEFAULTS:
            return SIMPLE_DEFAULTS[t]
        if t.startswith("[") and ":" in t:
            return "[:]"
        if t.startswith("["):
            return "[]"
        if t in record_names:
            return f"{t}.neoEmpty"
        if t in enum_info:
            first = enum_info[t][0]
            if not first[1]:
                return f".{first[0]}"
        return "REQUIRED"

    outp = []
    outp.append("// Generated by scripts/import-types.py from the sibling app's UniFFI bindings.")
    outp.append("// Do not edit by hand; re-run the script instead.")
    outp.append("// swiftlint:disable all")
    outp.append("import Foundation\n")
    for c in chunks:
        outp.append(c + "\n")

    outp.append("// MARK: - Sendable\n")
    for name, _ in records:
        outp.append(f"extension {name}: Sendable {{}}")
    for name, _ in enums:
        outp.append(f"extension {name}: Sendable {{}}")
    outp.append("extension QbtError: Sendable {}\n")

    outp.append("// MARK: - Codable records\n")
    for name, fields in records:
        outp.append(f"extension {name}: Codable {{")
        outp.append("    enum CodingKeys: String, CodingKey {")
        outp.append("        case " + ", ".join(esc(f) for f, _ in fields))
        outp.append("    }\n")
        outp.append(f"    static var neoEmpty: {name} {{")
        outp.append(f"        (try? JSONDecoder().decode({name}.self, from: Data(\"{{}}\".utf8)))!")
        outp.append("    }\n")
        outp.append("    public init(from decoder: any Decoder) throws {")
        outp.append("        let c = try decoder.container(keyedBy: CodingKeys.self)")
        args = []
        for i, (f, t) in enumerate(fields):
            t = t.strip()
            d = default_for(t)
            v = f"v{i}"
            if d is None:
                outp.append(f"        let {v}: {t} = try c.decodeIfPresent({t[:-1]}.self, forKey: .{esc(f)})")
            elif d == "REQUIRED":
                outp.append(f"        let {v}: {t} = try c.decode({t}.self, forKey: .{esc(f)})")
            else:
                outp.append(f"        let {v}: {t} = try c.decodeIfPresent({t}.self, forKey: .{esc(f)}) ?? {d}")
            args.append(f"{f}: {v}")
        outp.append("        self.init(\n            " + ",\n            ".join(args) + "\n        )")
        outp.append("    }")
        outp.append("}\n")

    outp.append("// MARK: - Codable enums\n")
    for name, cases in enums:
        if all(not params for _, params in cases):
            outp.append(f"extension {name}: Codable {{")
            outp.append("    public init(from decoder: any Decoder) throws {")
            outp.append("        let value = try decoder.singleValueContainer().decode(String.self)")
            outp.append("        switch value {")
            for c, _ in cases:
                outp.append(f"        case \"{c.strip('`')}\": self = .{c}")
            outp.append(f"        default: throw DecodingError.dataCorrupted(.init(codingPath: decoder.codingPath, debugDescription: \"Unknown {name} \\(value)\"))")
            outp.append("        }")
            outp.append("    }\n")
            outp.append("    public func encode(to encoder: any Encoder) throws {")
            outp.append("        var c = encoder.singleValueContainer()")
            outp.append("        switch self {")
            for c, _ in cases:
                outp.append(f"        case .{c}: try c.encode(\"{c.strip('`')}\")")
            outp.append("        }")
            outp.append("    }")
            outp.append("}\n")
        else:
            outp.append(f"extension {name}: Codable {{}}\n")

    open(out, "w", encoding="utf-8").write("\n".join(outp))
    print(f"{len(records)} records, {len(enums)} enums -> {out}")


if __name__ == "__main__":
    main()
